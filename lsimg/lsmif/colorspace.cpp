any2rgb::any2rgb(int color_mode)
{
	register int i;

	// Allocate the tables.
	red = (double*)malloc(3 * 256 * sizeof(double));
	green = (double*)malloc(3 * 256 * sizeof(double));
	blue = (double*)malloc(3 * 256 * sizeof(double));
	range_table = (BYTE*)malloc(4 * 256 * sizeof(BYTE));

	// Initialize tables.
	for (i = 0; i < 256; i++)
	{
		range_table[i] = 0;
		range_table[i + 256] = (BYTE)i;
		range_table[i + 512] = 255;
	}
	for (i = 0; i < 256; i++)
		range_table[i + 256 * 3] = 255;
	range_limit = range_table + 256;

	switch (color_mode)
	{
		case clrspcOHTA:
			// R = I1+1.00000*I2-0.66668*I3
			// G = I1+0.00000*I2+1.33333*I3
			// B = I1-1.00000*I2-0.66668*I3
			// I and Q, normally -0.5 through 0.5, must be normalized to the range 0
			// through MaxRGB.
			for (i = 0; i < 256; i++)
			{
				red[i+R]=i;
				green[i+R]=0.5*(2.0*i-255);
				blue[i+R]=(-0.33334)*(2.0*i-255);
				red[i+G]=i;
				green[i+G]=0.0;
				blue[i+G]=0.666665*(2.0*i-255);
				red[i+B]=i;
				green[i+B]=(-0.5)*(2.0*i-255);
				blue[i+B]=(-0.33334)*(2.0*i-255);
			}
			break;

		case clrspcsRGB:
			// R = Y            +1.032096*C2
			// G = Y-0.326904*C1-0.704445*C2
			// B = Y+1.685070*C1
			// sRGB is scaled by 1.3584.  C1 zero is 156 and C2 is at 137.

			for (i = 0; i < 256; i++)
			{
				red[i+R]=1.40200*i;
				green[i+R]=0.0;
				blue[i+R]=1.88000*(i-(double)137);
				red[i+G]=1.40200*i;
				green[i+G]=(-0.444066)*(i-(double)156);
				blue[i+G]=(-0.95692)*(i-(double)137);
				red[i+B]=1.40200*i;
				green[i+B]=2.28900*(i-(double)156);
				blue[i+B]=0.0;
				range_table[i + 256] = (BYTE)sRGBMap[i];
			}
			for ( ; i < 351; i++)
				range_table[i+256]=(BYTE)sRGBMap[i];
			break;

		case clrspcXYZ:
			// R =  3.240479*R-1.537150*G-0.498535*B
			// G = -0.969256*R+1.875992*G+0.041556*B
			// B =  0.055648*R-0.204043*G+1.057311*B
			for (i = 0; i < 256; i++)
			{
				red[i+R]=3.240479*i;
				green[i+R]=(-1.537150)*i;
				blue[i+R]=(-0.498535)*i;
				red[i+G]=(-0.969256)*i;
				green[i+G]=1.875992*i;
				blue[i+G]=0.041556*i;
				red[i+B]=0.055648*i;
				green[i+B]=(-0.204043)*i;
				blue[i+B]=1.057311*i;
			}
			break;

		case clrspcYCbCr:
			// R = Y            +1.402000*Cr
			// G = Y-0.344136*Cb-0.714136*Cr
			// B = Y+1.772000*Cb
			// Cb and Cr, normally -0.5 through 0.5, must be normalized to the range 0
			// through MaxRGB.
			for (i = 0; i < 256; i++)
			{
				red[i+R]=i;
				green[i+R]=0.0;
				blue[i+R]=0.701*(2.0*i-255);
				red[i+G]=i;
				green[i+G]=(-0.172068)*(2.0*i-255);
				blue[i+G]=(-0.357068)*(2.0*i-255);
				red[i+B]=i;
				green[i+B]=0.886*(2.0*i-255);
				blue[i+B]=0.0;
			}
			break;

		case clrspcYCC:
			// R = Y            +1.340762*C2
			// G = Y-0.317038*C1-0.682243*C2
			// B = Y+1.632639*C1
			// YCC is scaled by 1.3584.  C1 zero is 156 and C2 is at 137.
			for (i = 0; i < 256; i++)
			{
				red[i+R]=1.3584*i;
				green[i+R]=0.0;
				blue[i+R]=1.8215*(i-(double)137);
				red[i+G]=1.3584*i;
				green[i+G]=(-0.4302726)*(i-(double)156);
				blue[i+G]=(-0.9271435)*(i-(double)137);
				red[i+B]=1.3584*i;
				green[i+B]=2.2179*(i-(double)156);
				blue[i+B]=0.0;
				range_table[i+256]=(BYTE)YCCMap[i];
			}
			for ( ; i < 351; i++)
				range_table[i+256]=(BYTE)YCCMap[i];
			break;

		case clrspcYIQ:
			// R = Y+0.95620*I+0.62140*Q
			// G = Y-0.27270*I-0.64680*Q
			// B = Y-1.10370*I+1.70060*Q
			// I and Q, normally -0.5 through 0.5, must be normalized to the range 0
			// through MaxRGB.
			for (i = 0; i < 256; i++)
			{
				red[i+R]=i;
				green[i+R]=0.4781*(2.0*i-255);
				blue[i+R]=0.3107*(2.0*i-255);
				red[i+G]=i;
				green[i+G]=(-0.13635)*(2.0*i-255);
				blue[i+G]=(-0.3234)*(2.0*i-255);
				red[i+B]=i;
				green[i+B]=(-0.55185)*(2.0*i-255);
				blue[i+B]=0.8503*(2.0*i-255);
			}
			break;

		case clrspcYPbPr:
			// R = Y            +1.402000*C2
			// G = Y-0.344136*C1+0.714136*C2
			// B = Y+1.772000*C1
			// Pb and Pr, normally -0.5 through 0.5, must be normalized to the range 0
			// through MaxRGB.
			for (i = 0; i < 256; i++)
			{
				red[i+R]=i;
				green[i+R]=0.0;
				blue[i+R]=0.701*(2.0*i-255);
				red[i+G]=i;
				green[i+G]=(-0.172068)*(2.0*i-255);
				blue[i+G]=0.357068*(2.0*i-255);
				red[i+B]=i;
				green[i+B]=0.886*(2.0*i-255);
				blue[i+B]=0.0;
			}
			break;

		case clrspcYUV:
		default:
			// R = Y          +1.13980*V
			// G = Y-0.39380*U-0.58050*V
			// B = Y+2.02790*U
			// U and V, normally -0.5 through 0.5, must be normalized to the range 0
			// through MaxRGB.
			for (i = 0; i < 256; i++)
			{
				red[i+R]=i;
				green[i+R]=0.0;
				blue[i+R]=0.5699*(2.0*i-255);
				red[i+G]=i;
				green[i+G]=(-0.1969)*(2.0*i-255);
				blue[i+G]=(-0.29025)*(2.0*i-255);
				red[i+B]=i;
				green[i+B]=1.01395*(2.0*i-255);
				blue[i+B]=0;
			}
			break;
	}
}

any2rgb::~any2rgb()
{
	free(range_table);
	free(blue);
	free(green);
	free(red);
}

void any2rgb::xfer(BYTE* p)
{
	int x = p[0];
	int y = p[1];
	int z = p[2];
	p[0] = range_limit[(int) (red[x+R]+green[y+R]+blue[z+R])];
	p[1] = range_limit[(int) (red[x+G]+green[y+G]+blue[z+G])];
	p[2] = range_limit[(int) (red[x+B]+green[y+B]+blue[z+B])];
}
