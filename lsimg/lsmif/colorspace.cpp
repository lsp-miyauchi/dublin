#define X	0
#define Y	256
#define Z	512

rgb2any::rgb2any(int color_mode)
{
	register int i;
	x = (double*)malloc(3 * 256 * sizeof(double));
	y = (double*)malloc(3 * 256 * sizeof(double));
	z = (double*)malloc(3 * 256 * sizeof(double));
	range_table = (BYTE*)malloc(4 * 256 * sizeof(BYTE));

	// Pre-compute conversion tables.
	for (i = 0; i < 256; i++)
	{
		range_table[i] = 0;
		range_table[i + 256] = (BYTE)i;
		range_table[i + 512] = 255;
	}
	for (i = 0; i < 256; i++)
		range_table[i + 256 * 3] = 255;
	range_limit = range_table + 256;

	tx=0;
	ty=0;
	tz=0;
	switch (color_mode)
	{
		case clrspcOHTA:
			// I1 = 0.33333*R+0.33334*G+0.33333*B
			// I2 = 0.50000*R+0.00000*G-0.50000*B
			// I3 =-0.25000*R+0.50000*G-0.25000*B
			// I and Q, normally -0.5 through 0.5, are normalized to the range 0
			// through MaxRGB.
			ty = 256 >> 1;
			tz = 256 >> 1;
			for (i = 0; i < 256; i++)
			{
				x[i+X]=0.33333*i;
				y[i+X]=0.33334*i;
				z[i+X]=0.33333*i;
				x[i+Y]=0.5*i;
				y[i+Y]=0.0;
				z[i+Y]=(-0.5)*i;
				x[i+Z]=(-0.25)*i;
				y[i+Z]=0.5*i;
				z[i+Z]=(-0.25)*i;
			}
			break;

		case clrspcsRGB:
			// Y =  0.29900*R+0.58700*G+0.11400*B
			// C1= -0.29900*R-0.58700*G+0.88600*B
			// C2=  0.70100*R-0.58700*G-0.11400*B
			// sRGB is scaled by 1.3584.  C1 zero is 156 and C2 is at 137.
			ty = 156;
			tz = 137;
			for (i = 0; i <= (int)(0.018 * 255); i++)
			{
				x[i+X]=0.003962014134275617*255*i;
				y[i+X]=0.007778268551236748*255*i;
				z[i+X]=0.001510600706713781*255*i;
				x[i+Y]=(-0.002426619775463276)*255*i;
				y[i+Y]=(-0.004763965913702149)*255*i;
				z[i+Y]=0.007190585689165425*255*i;
				x[i+Z]=0.006927257754597858*255*i;
				y[i+Z]=(-0.005800713697502058)*255*i;
				z[i+Z]=(-0.0011265440570958)*255*i;
			}

			for ( ; i < 256; i++)
			{
				x[i+X]=0.2201118963486454*(1.099*i-0.099);
				y[i+X]=0.4321260306242638*(1.099*i-0.099);
				z[i+X]=0.08392226148409894*(1.099*i-0.099);
				x[i+Y]=(-0.1348122097479598)*(1.099*i-0.099);
				y[i+Y]=(-0.2646647729834528)*(1.099*i-0.099);
				z[i+Y]=0.3994769827314126*(1.099*i-0.099);
				x[i+Z]=0.3848476530332144*(1.099*i-0.099);
				y[i+Z]=(-0.3222618720834477)*(1.099*i-0.099);
				z[i+Z]=(-0.06258578094976668)*(1.099*i-0.099);
			}
			break;

		case clrspcXYZ:
			// X = 0.412453*X+0.357580*Y+0.180423*Z
			// Y = 0.212671*X+0.715160*Y+0.072169*Z
			// Z = 0.019334*X+0.119193*Y+0.950227*Z
			for (i = 0; i < 256; i++)
			{
				x[i+X]=0.412453*i;
				y[i+X]=0.35758*i;
				z[i+X]=0.180423*i;
				x[i+Y]=0.212671*i;
				y[i+Y]=0.71516*i;
				z[i+Y]=0.072169*i;
				x[i+Z]=0.019334*i;
				y[i+Z]=0.119193*i;
				z[i+Z]=0.950227*i;
			}
			break;

		case clrspcYCbCr:
			// Y =  0.299000*R+0.587000*G+0.114000*B
			// Cb= -0.168736*R-0.331264*G+0.500000*B
			// Cr=  0.500000*R-0.418688*G-0.081312*B
			// Cb and Cr, normally -0.5 through 0.5, are normalized to the range 0
			// through MaxRGB.
			ty = 256 >> 1;
			tz = 256 >> 1;
			for (i = 0; i < 256; i++)
			{
				x[i+X]=0.299*i;
				y[i+X]=0.587*i;
				z[i+X]=0.114*i;
				x[i+Y]=(-0.16873)*i;
				y[i+Y]=(-0.331264)*i;
				z[i+Y]=0.5*i;
				x[i+Z]=0.5*i;
				y[i+Z]=(-0.418688)*i;
				z[i+Z]=(-0.081312)*i;
			}
			break;

		case clrspcYCC:
			// Y =  0.29900*R+0.58700*G+0.11400*B
			// C1= -0.29900*R-0.58700*G+0.88600*B
			// C2=  0.70100*R-0.58700*G-0.11400*B
			// YCC is scaled by 1.3584.  C1 zero is 156 and C2 is at 137.

			ty = 156;
			tz = 137;
			for (i = 0; i <= (int)(0.018 * 255); i++)
			{
				x[i+X]=0.003962014134275617 * 255 * i;
				y[i+X]=0.007778268551236748 * 255 * i;
				z[i+X]=0.001510600706713781 * 255 * i;
				x[i+Y]=(-0.002426619775463276) * 255 * i;
				y[i+Y]=(-0.004763965913702149) * 255 * i;
				z[i+Y]=0.007190585689165425 * 255 * i;
				x[i+Z]=0.006927257754597858 * 255 * i;
				y[i+Z]=(-0.005800713697502058) * 255 * i;
				z[i+Z]=(-0.0011265440570958) * 255 * i;
			}
			for ( ; i < 256; i++)
			{
				x[i+X]=0.2201118963486454*(1.099*i-0.099);
				y[i+X]=0.4321260306242638*(1.099*i-0.099);
				z[i+X]=0.08392226148409894*(1.099*i-0.099);
				x[i+Y]=(-0.1348122097479598)*(1.099*i-0.099);
				y[i+Y]=(-0.2646647729834528)*(1.099*i-0.099);
				z[i+Y]=0.3994769827314126*(1.099*i-0.099);
				x[i+Z]=0.3848476530332144*(1.099*i-0.099);
				y[i+Z]=(-0.3222618720834477)*(1.099*i-0.099);
				z[i+Z]=(-0.06258578094976668)*(1.099*i-0.099);
			}
			break;

		case clrspcYIQ:
			// Y = 0.29900*R+0.58700*G+0.11400*B
			// I = 0.59600*R-0.27400*G-0.32200*B
			// Q = 0.21100*R-0.52300*G+0.31200*B
			// I and Q, normally -0.5 through 0.5, are normalized to the range 0
			// through MaxRGB.
			ty = 256 >> 1;
			tz = 256 >> 1;
			for (i = 0; i < 256; i++)
			{
				x[i+X]=0.299*i;
				y[i+X]=0.587*i;
				z[i+X]=0.114*i;
				x[i+Y]=0.596*i;
				y[i+Y]=(-0.274)*i;
				z[i+Y]=(-0.322)*i;
				x[i+Z]=0.211*i;
				y[i+Z]=(-0.523)*i;
				z[i+Z]=0.312*i;
			}
			break;

		case clrspcYPbPr:
			// Y =  0.299000*R+0.587000*G+0.114000*B
			// Pb= -0.168736*R-0.331264*G+0.500000*B
			// Pr=  0.500000*R-0.418688*G-0.081312*B
			// Pb and Pr, normally -0.5 through 0.5, are normalized to the range 0
			// through MaxRGB.
			ty = 256 >> 1;
			tz = 256 >> 1;
			for (i = 0; i < 256; i++)
			{
				x[i+X]=0.299*i;
				y[i+X]=0.587*i;
				z[i+X]=0.114*i;
				x[i+Y]=(-0.168736)*i;
				y[i+Y]=(-0.331264)*i;
				z[i+Y]=0.5*i;
				x[i+Z]=0.5*i;
				y[i+Z]=(-0.418688)*i;
				z[i+Z]=(-0.081312)*i;
			}
			break;

		case clrspcYUV:
		default:
			// Y =  0.29900*R+0.58700*G+0.11400*B
			// U = -0.14740*R-0.28950*G+0.43690*B
			// V =  0.61500*R-0.51500*G-0.10000*B
			// U and V, normally -0.5 through 0.5, are normalized to the range 0
			// through MaxRGB.  Note that U = 0.493*(B-Y), V = 0.877*(R-Y).
			ty = 256 >> 1;
			tz = 256 >> 1;
			for (i = 0; i < 256; i++)
			{
				x[i+X]=0.299*i;
				y[i+X]=0.587*i;
				z[i+X]=0.114*i;
				x[i+Y]=(-0.1474)*i;
				y[i+Y]=(-0.2895)*i;
				z[i+Y]=0.4369*i;
				x[i+Z]=0.615*i;
				y[i+Z]=(-0.515)*i;
				z[i+Z]=(-0.1)*i;
			}
			break;
	}
}

rgb2any::~rgb2any()
{
	free(x);
	free(y);
	free(z);
	free(range_table);
}

void rgb2any::xfer(BYTE* p)
{
	int red = p[0];
	int green = p[1];
	int blue = p[2];
	p[0] = range_limit[(int)(x[red+X] + y[green+X] + z[blue+X] + tx)];
	p[1] = range_limit[(int)(x[red+Y] + y[green+Y] + z[blue+Y] + ty)];
	p[2] = range_limit[(int)(x[red+Z] + y[green+Z] + z[blue+Z] + tz)];
}


