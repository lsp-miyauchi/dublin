HPALETTE make_default_palette(int index)
{
	LOGPALETTE* plg =
		(LOGPALETTE*)malloc(sizeof(LOGPALETTE) + sizeof(PALETTEENTRY) * 256);
	plg->palVersion = 0x300;

	const COLORREF* data;
	switch (index) {
		case 1:
			plg->palNumEntries = sizeof(pal_mac) / sizeof(COLORREF);
			data = pal_mac;
			break;

		case 2:
			plg->palNumEntries = sizeof(pal_spc) / sizeof(COLORREF);
			data = pal_spc;
			break;

		case 3:
			plg->palNumEntries = sizeof(pal_pastel) / sizeof(COLORREF);
			data = pal_pastel;
			break;

		case 4:
			plg->palNumEntries = sizeof(pal_kok) / sizeof(COLORREF);
			data = pal_kok;
			break;

		case 5:
			plg->palNumEntries = sizeof(pal_cold) / sizeof(COLORREF);
			data = pal_cold;
			break;

		case 6:
			plg->palNumEntries = sizeof(pal_web) / sizeof(COLORREF);
			data = pal_web;
			break;

		case 7:
			plg->palNumEntries = sizeof(pal_gold) / sizeof(COLORREF);
			data = pal_gold;
			break;

		case 0:
		default:
			plg->palNumEntries = sizeof(pal_win) / sizeof(COLORREF);
			data = pal_win;
			break;
	}

	for (int i = 0; i < plg->palNumEntries; i++) {
		plg->palPalEntry[i].peRed = GetRValue(*data);
		plg->palPalEntry[i].peGreen = GetGValue(*data);
		plg->palPalEntry[i].peBlue = GetBValue(*data);
		plg->palPalEntry[i].peFlags = 0;
		data++;
	}

	HPALETTE hpal = CreatePalette(plg);
	free(plg);

	return hpal;
}
